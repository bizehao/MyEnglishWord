using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using WordNetSqlite;

namespace MyEnglishWord.Core.DataBase;

/// <summary>
/// Owns the WordNet database of the app: it unpacks the SQLite dictionary that ships as an
/// embedded resource on first use and keeps the searchable database and the lemma dictionary
/// that the query suggestions are built from.
/// </summary>
internal class WordnetManager
{
    /// <summary>The embedded resource generated by WordNetSqliteDbGen from the WordNet dictionary.</summary>
    private const string DatabaseResourceName = "WordNetDict.db";

    private const string DatabaseFileName = "wordnet31.db";

    /// <summary>The path of the SQLite dictionary in the local app data folder.</summary>
    public static string DatasetPath
    {
        get; private set;
    }

    /// <summary>The opened dictionary. Only available after <see cref="PrepareDatasetAsync"/>.</summary>
    public static WordNetDatabase Database
    {
        get; private set;
    }

    // Key is lemma but with hyphens replaced with underscores
    private static ImmutableDictionary<string, List<string>> _LemmaDict
    {
        get; set;
    }
    private static readonly SemaphoreSlim _PreparingDatasetSemaphore = new(1, 1);
    private static readonly SemaphoreSlim _PreparingLemmaDictSemaphore = new(1, 1);

    public static async Task PrepareDatasetAsync(string datasetPath)
    {
        await _PreparingDatasetSemaphore.WaitAsync();
        try
        {
            if (Database != null)
            {
                return;
            }

            var database = new WordNetDatabase(datasetPath);
            await database.InitializeAsync();

            DatasetPath = datasetPath;
            Database = database;
        }
        finally
        {
            _PreparingDatasetSemaphore.Release();
        }
    }

    public static async Task<ImmutableDictionary<string, List<string>>> GetLemmaDictAsync()
    {
        await _PreparingLemmaDictSemaphore.WaitAsync();
        try
        {
            if (_LemmaDict == null)
            {
                await PrepareLemmaDictAsync();
            }
            Debug.Assert(_LemmaDict != null);
            return _LemmaDict;
        }
        finally
        {
            _PreparingLemmaDictSemaphore.Release();
        }
    }

    /// <summary>
    /// Reads every lemma of the database to build the dictionary the query suggestions are
    /// matched against. The lemmas used to be parsed out of the index files of the dictionary.
    /// </summary>
    public static async Task PrepareLemmaDictAsync()
    {
        await _PreparingLemmaDictSemaphore.WaitAsync();
        try
        {
            if (_LemmaDict != null)
            {
                return;
            }

            var database = Database;
            if (database == null)
            {
                throw new InvalidOperationException($"{nameof(PrepareDatasetAsync)} must run first");
            }

            var lemmas = new Dictionary<string, List<string>>();
            foreach (var pos in new[]
            {
                PartOfSpeech.Adj,
                PartOfSpeech.Adv,
                PartOfSpeech.Noun,
                PartOfSpeech.Verb,
            })
            {
                foreach (var lemma in await database.GetIndexLemmasAsync(pos))
                {
                    var searchTerm = lemma.Replace('-', '_');
                    if (!lemmas.TryGetValue(searchTerm, out var lemmasOfThisSearchTerm))
                    {
                        lemmasOfThisSearchTerm = new List<string>();
                        lemmas.Add(searchTerm, lemmasOfThisSearchTerm);
                    }

                    if (!lemmasOfThisSearchTerm.Contains(lemma))
                    {
                        lemmasOfThisSearchTerm.Add(lemma);
                    }
                }
            }

            _LemmaDict = lemmas.ToImmutableDictionary();
        }
        finally
        {
            _PreparingLemmaDictSemaphore.Release();
        }
    }
}
